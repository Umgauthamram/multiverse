import { describe, it, expect, vi } from "vitest";
import {
  compileRoll,
  compileCalc,
  compileClamp,
  compileStatus,
  compileQuarterStage,
  compileQuarterStageToLines,
  detectHitStat,
} from "@/lib/scene/sceneCompiler";
import { formatLine, parseLine } from "@/lib/scene/sceneLanguage";
import { LifeEvent } from "@/lib/simulation/eventRoller";
import { LifeStats } from "@/lib/simulation/statClamper";
import { resolveBranchColor } from "@/lib/simulation/branchColorEngine";
import { runQuarterStep } from "@/lib/simulation/timelineRunner";
import { QuarterDelta } from "@/lib/ai/agents/lifeAgent";
import { LanguageModel } from "ai";

describe("Phase 1: Scene Compiler", () => {
  const dummyEvent: LifeEvent = {
    type: "promotion",
    title: "Promotion to Principal",
    description: "Earned promotion with higher base and stock grant.",
    severity: "positive",
    statDeltas: { deltaHappiness: 5, deltaHealth: -2, deltaRelationships: 0, deltaCareer: 12 },
    financialImpact: {
      incomeMultiplier: 1.25,
      lumpSumExpense: 500,
      lumpSumWindfall: 3500,
    },
  };

  it("is pure and deterministic: same record produces byte-identical lines", () => {
    const stats: LifeStats = { happiness: 75, health: 68, relationships: 60, career: 82 };

    const lineA1 = formatLine(compileRoll("S1", 4, dummyEvent));
    const lineA2 = formatLine(compileRoll("S1", 4, dummyEvent));
    expect(lineA1).toBe(lineA2);

    const calc1 = formatLine(compileCalc("S2", 3, 20000, 6000, 3000, 1000, 27000));
    const calc2 = formatLine(compileCalc("S2", 3, 20000, 6000, 3000, 1000, 27000));
    expect(calc1).toBe(calc2);

    const clamp1 = formatLine(compileClamp("S3", 5, stats));
    const clamp2 = formatLine(compileClamp("S3", 5, stats));
    expect(clamp1).toBe(clamp2);
  });

  it("correctly computes evc math (lumpSumWindfall - lumpSumExpense)", () => {
    const windfall = 5000;
    const expense = 1200;
    const evc = windfall - expense; // 3800

    const calcLine = compileCalc("S1", 2, 10000, 4000, 2000, evc, 16800);
    expect(calcLine.args.evc).toBe(3800);

    const formatted = formatLine(calcLine);
    expect(formatted).toContain("evc=3800");

    const parsed = parseLine(formatted);
    expect(parsed?.args.evc).toBe(3800);
  });

  it("detects hit stat accurately when stats hit 0 or 100 boundaries, prioritizing joy -> hp -> rel -> car", () => {
    expect(detectHitStat({ happiness: 100, health: 70, relationships: 70, career: 70 })).toBe("joy");
    expect(detectHitStat({ happiness: 0, health: 70, relationships: 70, career: 70 })).toBe("joy");

    expect(detectHitStat({ happiness: 80, health: 100, relationships: 70, career: 70 })).toBe("hp");
    expect(detectHitStat({ happiness: 80, health: 0, relationships: 70, career: 70 })).toBe("hp");

    expect(detectHitStat({ happiness: 80, health: 80, relationships: 100, career: 70 })).toBe("rel");
    expect(detectHitStat({ happiness: 80, health: 80, relationships: 0, career: 70 })).toBe("rel");

    expect(detectHitStat({ happiness: 80, health: 80, relationships: 80, career: 100 })).toBe("car");
    expect(detectHitStat({ happiness: 80, health: 80, relationships: 80, career: 0 })).toBe("car");

    expect(detectHitStat({ happiness: 50, health: 50, relationships: 50, career: 50 })).toBe("none");
  });

  it("STATUS generated by the compiler strictly agrees with resolveBranchColor", () => {
    const testCases: { stats: LifeStats; isBurnout?: boolean }[] = [
      { stats: { happiness: 85, health: 80, relationships: 75, career: 80 } }, // Thriving
      { stats: { happiness: 55, health: 55, relationships: 55, career: 55 } }, // Plateau
      { stats: { happiness: 25, health: 25, relationships: 40, career: 40 } }, // Struggling
      { stats: { happiness: 10, health: 10, relationships: 20, career: 20 }, isBurnout: true }, // Burnout
    ];

    for (const { stats, isBurnout } of testCases) {
      const expectedStatus = resolveBranchColor(stats, isBurnout).status;
      const statusLine = compileStatus("S1", 1, stats, isBurnout);
      expect(statusLine.args.st).toBe(expectedStatus);
      expect(statusLine.args.burn).toBe(isBurnout ? 1 : 0);
    }
  });

  it("produces full stage scene lines through compileQuarterStage", () => {
    const stages = compileQuarterStage("clamp", {
      storyId: "S2",
      quarter: 4,
      clampedStats: { happiness: 70, health: 70, relationships: 70, career: 70 },
      isBurnout: false,
    });

    expect(stages.length).toBe(2);
    expect(stages[0].verb).toBe("CLAMP");
    expect(stages[1].verb).toBe("STATUS");
  });

  it("enforces zero additional LLM calls: running a 20-quarter story yields exactly 20 calls", async () => {
    let callCount = 0;

    const mockExecutor = vi.fn(async () => {
      callCount++;
      const delta: QuarterDelta = {
        quarter: callCount,
        deltaHappiness: 2,
        deltaHealth: -1,
        deltaRelationships: 1,
        deltaCareer: 3,
        diaryEntry: `Simulated reflection for quarter ${callCount}.`,
        reflection: `Tradeoff balancing quarter ${callCount}.`,
      };
      return { object: delta };
    });

    let currentStats: LifeStats = { happiness: 65, health: 70, relationships: 65, career: 60 };
    let currentSavings = 25000;
    const generatedSceneLines: string[] = [];

    const dummyModel = { modelId: "dummy-model", provider: "dummy" } as unknown as LanguageModel;
    const mockChain = [{ name: "groq" as const, getModel: () => dummyModel }];

    // Run 20 quarters sequentially
    for (let q = 1; q <= 20; q++) {
      const step = await runQuarterStep({
        sessionId: "test-sess",
        timelineId: "S1",
        branchOption: "A",
        branchName: "London AI Startup",
        branchLocation: "London, UK",
        personaSeed: "bold",
        decisionPrompt: "Should I join?",
        quarter: q,
        currentStats,
        currentSavings,
        monthlyIncome: 5000,
        monthlyExpenses: 2500,
        persistToDb: false,
        customChain: mockChain,
        executor: mockExecutor,
      });

      // Pure scene compiler generates lines alongside the step
      const rollLines = compileQuarterStageToLines("roll", {
        storyId: "S1",
        quarter: q,
        rolledEvent: step.rolledEvent,
      });
      const calcLines = compileQuarterStageToLines("calc", {
        storyId: "S1",
        quarter: q,
        finance: {
          startingSavings: currentSavings,
          effectiveMonthlyIncome: 5000,
          monthlyBaseExpenses: 2500,
          netEventCashImpact: 0,
          endingSavings: step.endingSavings,
        },
      });
      const clampLines = compileQuarterStageToLines("clamp", {
        storyId: "S1",
        quarter: q,
        clampedStats: step.stats,
        isBurnout: step.isBurnedOut,
      });
      const sayLines = compileQuarterStageToLines("say", {
        storyId: "S1",
        quarter: q,
        diaryText: step.diaryEntry,
      });

      generatedSceneLines.push(...rollLines, ...calcLines, ...clampLines, ...sayLines);

      currentStats = step.stats;
      currentSavings = step.endingSavings;
    }

    // Exactly 20 calls to the LLM executor
    expect(callCount).toBe(20);
    expect(mockExecutor).toHaveBeenCalledTimes(20);

    // Scene lines compiled for all 20 quarters
    expect(generatedSceneLines.length).toBeGreaterThanOrEqual(100);
    expect(generatedSceneLines.every((l) => typeof l === "string" && l.length <= 280)).toBe(true);
  });
});
